#!/usr/bin/env python3
"""Generate platform/console_names.inc (name tables for the debug console) from upstream's headers.

Three tables, so the console's names cannot drift from the enums they name:
  * EScriptObjectMessage (include/MetroidPrime/CEntityInfo.hpp), kSM_ stripped -> kMessageNames
  * EScriptObjectState   (include/MetroidPrime/CEntityInfo.hpp), kSS_ stripped -> kStateNames
  * EItemType            (include/MetroidPrime/Player/CPlayerState.hpp), kIT_ stripped and the
    first letter lowercased -> kItemNames

Only explicit initialisers (`kName = 0x1234,` or `kName = 12,`) are read: an enumerator without one
is skipped, and so is a negative value (0x80000000 and up, read as int): no value is inferred.
`//` comments are ignored.
A value named twice keeps the first name in declaration order; each table is sorted by name.

    python3 tools/gen_console_names.py            # rewrite platform/console_names.inc
    python3 tools/gen_console_names.py --check    # exit 1 (with a message) if it is stale
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
ENTITY_INFO = ROOT / "include" / "MetroidPrime" / "CEntityInfo.hpp"
PLAYER_STATE = ROOT / "include" / "MetroidPrime" / "Player" / "CPlayerState.hpp"
OUT = ROOT / "platform" / "console_names.inc"

# (header, enum, table name, prefix to strip, lowercase the first letter of what is left)
TABLES = [
    (ENTITY_INFO, "EScriptObjectMessage", "kMessageNames", "kSM_", False),
    (ENTITY_INFO, "EScriptObjectState", "kStateNames", "kSS_", False),
    (PLAYER_STATE, "EItemType", "kItemNames", "kIT_", True),
]

ENTRY_RE = re.compile(r"^\s*(k\w+)\s*=\s*(0x[0-9a-fA-F]+|\d+)\s*,")


def enum_body(text: str, enum: str) -> list:
    """The lines between `enum <enum> {` and its closing brace."""
    lines = text.splitlines()
    opener = re.compile(r"\benum\s+" + enum + r"\s*\{")
    start = next((i for i, line in enumerate(lines) if opener.search(line)), None)
    if start is None:
        sys.exit(f"gen_console_names: enum {enum} not found")
    body = []
    for line in lines[start + 1:]:
        if line.strip().startswith("}"):
            return body
        body.append(line)
    sys.exit(f"gen_console_names: enum {enum} is not closed")


def table_entries(header: pathlib.Path, enum: str, prefix: str, lower_first: bool) -> list:
    """(value, name) pairs, in declaration order, first name kept per value."""
    seen = {}
    for line in enum_body(header.read_text(), enum):
        code = line.split("//", 1)[0]
        match = ENTRY_RE.match(code)
        if match is None or not match.group(1).startswith(prefix):
            continue
        value = int(match.group(2), 0)
        if value >= 0x80000000:
            # kSS_InvalidState = 0xffffffff and kSM_None = 0xffffffff: -1 in the enum's int type.
            continue
        name = match.group(1)[len(prefix):]
        if lower_first and name:
            name = name[0].lower() + name[1:]
        seen.setdefault(value, name)
    return list(seen.items())


def render() -> str:
    out = ["// Generated by tools/gen_console_names.py - do not edit.\n"]
    for header, enum, table, prefix, lower_first in TABLES:
        entries = sorted(table_entries(header, enum, prefix, lower_first), key=lambda e: e[1])
        out.append(f"static const SEnumName {table}[] = {{\n")
        for value, name in entries:
            out.append(f'  {{0x{value:08x}, "{name}"}},\n')
        out.append("};\n")
    return "".join(out)


if __name__ == "__main__":
    new = render()
    if "--check" in sys.argv:
        if OUT.exists() and OUT.read_text() == new:
            sys.exit(0)
        print(f"{OUT.relative_to(ROOT)} is stale: run tools/gen_console_names.py", file=sys.stderr)
        sys.exit(1)
    OUT.write_text(new)
