#!/usr/bin/env python3
"""Generate platform/port_save_trilogy_tables.inc: the G2ME <-> R3ME save-slot conversion tables.

  python3 -I tools/trilogy_tables.py [G2ME01=<files>] [R3ME01=<files>] [--out platform/port_save_trilogy_tables.inc]

Reads the MLVL, SAVW and HINT_Hints assets of the two discs through tools/savw_diff.py. Per
release it writes the world rows (MemoryWorlds order, i.e. sorted by MLVL ID), the scan union,
the hint names and the signature. Per direction it writes, for each target entry, the index of
the source entry with the same ID (or -1): worlds (FrontEnd is 69802220 on the GameCube disc
and daea74a3 on Trilogy), scans, hints, relays, doors, unmappable areas, cinematics, and the
layers of the areas whose layer lists differ (matched by name).
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import savw_diff as sd  # noqa: E402

ALIASES = {0x69802220: 0xdaea74a3}  # FrontEnd, G2ME -> R3ME


def savw_of(rel, w):
    m = rel["mlvl"][w][0]
    return m, rel["savw"][m["savw"]]


def release_rows(rel, name):
    lines, rows = [], []
    for w in rel["worlds"]:
        m, s = savw_of(rel, w)
        n = "k%s_%08x" % (name, w)
        lines.append("static const uint8_t %s_layers[] = {%s};" % (n, ", ".join(str(c) for c in m["layerCounts"])))
        lines.append("static const uint64_t %s_defaults[] = {%s};" % (n, ", ".join("0x%xull" % d for d in m["layerDefaults"])))
        lines.append(sd.emit_array(n + "_cines", "uint32_t", s["cinematics"] or [0], "0x%08x"))
        rows.append("    {0x%08x, %d, %d, %d, %d, %d, %s_layers, %s_defaults, %s_cines}," % (
            w, s["areaCount"], len(s["relays"]), len(s["doors"]), len(s["unmappable"]),
            len(s["cinematics"]), n, n, n))
    return lines, rows


def emit(me, r3, path):
    rels = {"ME": me, "R3": r3}
    L = [
        "// Generated by tools/trilogy_tables.py; do not edit. Source: the extracted G2ME01 and R3ME01 paks",
        "// (MLVL, SAVW, HINT_Hints). Included once by port_save_trilogy_payload.cpp.",
        "",
        "struct STriWorld {",
        "  uint32_t mlvl;",
        "  uint16_t areas, relays, doors, unmappable, cinematics;",
        "  const uint8_t* layerCounts;     // per area",
        "  const uint64_t* layerDefaults;  // per area, bit i = layer i",
        "  const uint32_t* cinematicIds;",
        "};",
        "",
        "struct STriRelease {",
        "  const char* code;",
        "  uint32_t signature;",
        "  int worldCount;",
        "  const STriWorld* worlds;",
        "  int scanCount;  // the union without the 4 fixed entries",
        "  const uint32_t* scans;",
        "  int hintCount;",
        "  const char* const* hints;",
        "  int gameVarBits;",
        "  int cinematicBits;",
        "};",
        "",
        "struct STriLayerMap {",
        "  uint16_t world, area;",
        "  uint8_t count;",
        "  const int8_t* map;  // target layer -> source layer, -1 if new",
        "};",
        "",
        "struct STriWorldMap {  // indexed by target world; null = identical lists",
        "  const int16_t* relays;",
        "  const int16_t* doors;",
        "  const int16_t* unmappable;",
        "  const int16_t* cinematics;",
        "};",
        "",
        "struct STriDirection {",
        "  const STriRelease* from;",
        "  const STriRelease* to;",
        "  const int16_t* worldSource;  // per target world: the source world index, -1 if none",
        "  const STriWorldMap* worlds;  // per target world",
        "  const int16_t* scans;        // per target scan -> source scan or -1",
        "  const int16_t* hints;",
        "  int layerMapCount;",
        "  const STriLayerMap* layerMaps;",
        "};",
        "",
    ]
    for name, rel in rels.items():
        a, rows = release_rows(rel, name)
        L += a
        L.append("static const STriWorld k%sWorlds[] = {" % name)
        L += rows
        L.append("};")
        L.append(sd.emit_array("k%sScans" % name, "uint32_t", [sc[0] for sc in rel["scanUnion"]], "0x%08x"))
        L.append("static const char* const k%sHints[] = {%s};" % (name, ", ".join('"%s"' % x for x in rel["hint"]["names"])))
        L.append("")
    for name, rel, code in (("ME", me, "G2ME"), ("R3", r3, "R3ME")):
        L.append("static const STriRelease k%sRelease = {\"%s\", 0x%08x, %d, k%sWorlds, %d, k%sScans, %d, k%sHints, %d, %d};" % (
            name, code, rel["sigBE"], len(rel["worlds"]), name, len(rel["scanUnion"]), name,
            len(rel["hint"]["names"]), name, sd.envbits(rel["gamevars"]), rel["cinematicBits"]))
    L.append("")
    for a, b, tag, sn, dn in ((me, r3, "MEtoR3", "ME", "R3"), (r3, me, "R3toME", "R3", "ME")):
        fwd = ALIASES if tag == "MEtoR3" else {v: k for k, v in ALIASES.items()}
        assert a["sysvars"] == b["sysvars"] and a["gamevars"] == b["gamevars"]
        wsrc, wm_rows, layer_rows = [], [], []
        for ti, tw in enumerate(b["worlds"]):
            src = [w for w in a["worlds"] if fwd.get(w, w) == tw]
            assert len(src) <= 1
            si = a["worlds"].index(src[0]) if src else -1
            wsrc.append(si)
            if si < 0:
                wm_rows.append("    {nullptr, nullptr, nullptr, nullptr},")
                continue
            ma, sa = savw_of(a, src[0])
            mb, sb = savw_of(b, tw)
            assert sa["areaCount"] == sb["areaCount"], "area count differs in %08x" % tw
            names = []
            for key in ("relays", "doors", "unmappable", "cinematics"):
                mp = sd.maps_by_key(sb[key], sa[key])
                if mp is None:
                    names.append("nullptr")
                else:
                    n = "k%s_%s_%d" % (tag, key, ti)
                    L.append(sd.emit_array(n, "int16_t", mp))
                    names.append(n)
            wm_rows.append("    {%s}," % ", ".join(names))
            for ai in range(sa["areaCount"]):
                la, lb = sd.area_layers(ma, ai), sd.area_layers(mb, ai)
                if la != lb:
                    assert len(set(la)) == len(la) and len(set(lb)) == len(lb)
                    n = "k%s_layers_%d_%d" % (tag, ti, ai)
                    L.append(sd.emit_array(n, "int8_t", [la.index(k) if k in la else -1 for k in lb]))
                    layer_rows.append("    {%d, %d, %d, %s}," % (ti, ai, len(lb), n))
        sa_ids = [sc[0] for sc in a["scanUnion"]]
        sb_ids = [sc[0] for sc in b["scanUnion"]]
        sm = sd.maps_by_key(sb_ids, sa_ids)
        ha, hb = a["hint"]["names"], b["hint"]["names"]
        hm = sd.maps_by_key(hb, ha)
        L.append(sd.emit_array("k%s_worldSource" % tag, "int16_t", wsrc))
        L.append(sd.emit_array("k%s_scans" % tag, "int16_t", sm or list(range(len(sb_ids)))))
        L.append(sd.emit_array("k%s_hints" % tag, "int16_t", hm or list(range(len(hb)))))
        L.append("static const STriWorldMap k%s_worlds[] = {" % tag)
        L += wm_rows
        L.append("};")
        if layer_rows:
            L.append("static const STriLayerMap k%s_layerMaps[] = {" % tag)
            L += layer_rows
            L.append("};")
        L.append("static const STriDirection k%s = {&k%sRelease, &k%sRelease, k%s_worldSource, k%s_worlds, "
                 "k%s_scans, k%s_hints, %d, %s};" % (tag, sn, dn, tag, tag, tag, tag, len(layer_rows),
                                                      "k%s_layerMaps" % tag if layer_rows else "nullptr"))
        L.append("")
    with open(path, "w") as f:
        f.write("\n".join(L) + "\n")


def main(argv):
    out = "platform/port_save_trilogy_tables.inc"
    if "--out" in argv:
        i = argv.index("--out")
        out = argv[i + 1]
        argv = argv[:i] + argv[i + 2:]
    args = {"G2ME01": "/tmp/opencode/discs/G2ME01/files", "R3ME01": "/tmp/opencode/discs/R3ME01/DATA/files/MP2"}
    for a in argv:
        k, v = a.split("=", 1)
        args[k] = v
    emit(sd.load_release("G2ME01", args["G2ME01"]), sd.load_release("R3ME01", args["R3ME01"]), out)


if __name__ == "__main__":
    main(sys.argv[1:])
