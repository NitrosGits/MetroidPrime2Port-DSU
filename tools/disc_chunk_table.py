#!/usr/bin/env python3
"""Regenerates platform/port_disc_verify_table.inc: per known disc revision, its
size, SHA-1 and the CRC32 of every 1 MiB chunk (the last one partial), for the
in-app disc image check (platform/port_disc_verify.cpp). MP1's tool
(tools/disc_chunk_table.py there), for Echoes.

    python3 -I tools/disc_chunk_table.py [--out platform/port_disc_verify_table.inc] \
        usa100.iso [pal.iso]

Give each image as an uncompressed ISO (any order); the revision is read from
the header (game id at 0x0, version byte at 0x7). A table row records the image
it was built from: the check then says a copy "matches the record of <revision>"
and names the MiB and files that differ, which is what finds a truncated or
zeroed copy. The SHA-1 is printed so it can be compared with the release's.
"""
import hashlib
import sys
import zlib

CHUNK = 1 << 20
# What the port accepts: Echoes USA (G2ME01) and PAL (G2MP01), version 0.
REVISIONS = {
    (b"G2ME01", 0): "USA 1.00",
    (b"G2MP01", 0): "PAL",
}
ORDER = [(b"G2ME01", 0), (b"G2MP01", 0)]


def scan(path):
    sha = hashlib.sha1()
    crcs = []
    size = 0
    head = b""
    with open(path, "rb") as f:
        while True:
            buf = f.read(CHUNK)
            if not buf:
                break
            if not head:
                head = buf[:8]
            sha.update(buf)
            crcs.append(zlib.crc32(buf) & 0xFFFFFFFF)
            size += len(buf)
    return head, size, sha.hexdigest(), crcs


def main(argv):
    out = "platform/port_disc_verify_table.inc"
    args = argv[1:]
    if args[:1] == ["--out"]:
        out, args = args[1], args[2:]
    found = {}
    for path in args:
        head, size, sha, crcs = scan(path)
        key = (head[:6], head[7])
        if key not in REVISIONS:
            sys.exit(f"{path}: not a supported disc ({head[:6]!r}, version {head[7]})")
        print(f"{path}: {REVISIONS[key]}, {size} bytes, SHA-1 {sha}, {len(crcs)} chunks")
        found[key] = (REVISIONS[key], size, sha, crcs)
    if not found:
        sys.exit("no images given")
    lines = [
        "// Generated by tools/disc_chunk_table.py; do not edit.",
        "// Regenerate: python3 -I tools/disc_chunk_table.py usa100.iso [pal.iso]",
        "// Per revision: game id, version byte, name, size, SHA-1, then the CRC32 of each 1 MiB chunk.",
    ]
    for key in ORDER:
        if key not in found:
            continue
        name, size, sha, crcs = found[key]
        lines.append(f'{{"{key[0].decode()}", {key[1]}, "{name}", {size}ull, "{sha}", {len(crcs)}, {{')
        for i in range(0, len(crcs), 10):
            lines.append("    " + ", ".join(f"0x{c:08x}" for c in crcs[i:i + 10]) + ",")
        lines.append("}},")
    with open(out, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {out}")


main(sys.argv)
