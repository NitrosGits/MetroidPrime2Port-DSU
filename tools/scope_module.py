#!/usr/bin/env python3
"""Give each REL module its own symbol namespace in the host link.

On the console every REL is linked separately, so several modules can define RELMain/RELExit,
module-local Load* functions and weak template copies under the same names. A flat host link
cannot hold them. This tool is run by CMake (see mp_scope_modules in CMakeLists.txt) in two modes.

  registry  Read the module list (one line per module: "Name;obj;obj;...") and write the
            compiled-module registry include (name, prolog, epilog per module that defines
            RELMain/RELExit), which platform/compiled_modules.cpp includes.
  scope     For every module: partially link its objects (ld -r) into <outdir>/<Name>.o, rename
            RELMain/RELExit to mp_rel_<Name>_prolog/_epilog, and localize every other defined
            global/weak symbol except those that an object outside the module references and
            that nothing outside the module defines.

    scope_module.py registry --modules LIST --out INC
    scope_module.py scope --modules LIST --others LIST --outdir DIR --ld LD --objcopy OBJCOPY --nm NM
"""
import argparse
import os
import re
import subprocess
import sys

ENTRY = {"prolog": re.compile(r"^(_Z7RELMainv|RELMain)$"), "epilog": re.compile(r"^(_Z7RELExitv|RELExit)$")}


def read_modules(path):
    mods = []
    for line in open(path).read().splitlines():
        if line.strip():
            name, *objs = line.split(";")
            mods.append((name, [o for o in objs if o]))
    return mods


def nm(tool, objs, *flags):
    """Return {symbol: type} lists from nm -P over objs, in chunks to bound the command line."""
    out = []
    for i in range(0, len(objs), 200):
        r = subprocess.run([tool, "--no-demangle", "-P", *flags, *objs[i:i + 200]],
                           capture_output=True, text=True, check=True)
        for line in r.stdout.splitlines():
            parts = line.split()
            # "name type [value size]"; per-file header lines end in ':' and have one field.
            if len(parts) >= 2:
                out.append((parts[0], parts[1]))
    return out


def entry_points(nm_tool, objs):
    found = {}
    for sym, typ in nm(nm_tool, objs, "--defined-only", "-g"):
        for kind, rx in ENTRY.items():
            if typ in "TtWw" and rx.match(sym):
                found[kind] = sym
    return found


def registry(args):
    lines = ["// GENERATED by tools/scope_module.py - do not edit.\n"]
    decls, rows = [], []
    for name, objs in read_modules(args.modules):
        eps = entry_points(args.nm, objs)
        if "prolog" not in eps:
            continue
        decls.append(f"void mp_rel_{name}_prolog();")
        epilog = "nullptr"
        if "epilog" in eps:
            decls.append(f"void mp_rel_{name}_epilog();")
            epilog = f"&mp_rel_{name}_epilog"
        rows.append(f'    {{"{name}", "{name}", &mp_rel_{name}_prolog, {epilog}}},')
    lines.append('#ifdef MP_MODULE_DECLS\nextern "C" {\n' + "\n".join(decls) + "\n}\n#else")
    lines.append("constexpr CompiledModule kCompiledModules[] = {\n" + "\n".join(rows) + "\n};\n#endif\n")
    new = "\n".join(lines)
    if not os.path.exists(args.out) or open(args.out).read() != new:
        os.makedirs(os.path.dirname(args.out), exist_ok=True)
        open(args.out, "w").write(new)


def scope(args):
    mods = read_modules(args.modules)
    others = [l for l in open(args.others).read().splitlines() if l.strip()]
    all_module_objs = {o for _, objs in mods for o in objs}
    others = [o for o in others if o not in all_module_objs]

    defined_outside = {s for s, t in nm(args.nm, others, "--defined-only", "-g") if t not in "Uu"}
    undef_outside = {s for s, t in nm(args.nm, others, "-u") if t == "U"}
    os.makedirs(args.outdir, exist_ok=True)

    # Pass 1: partial links, so every module's own undefined references are known.
    partials = {}
    for name, objs in mods:
        partials[name] = os.path.join(args.outdir, f"{name}.raw.o")
        # --force-group-allocation dissolves COMDAT groups: their signature symbols are localized
        # below, but ld still folds groups by signature name, so a module's inline functions
        # (and DW.ref.__gxx_personality_v0) were discarded in favour of another object's group
        # while the module's own references stayed bound to the localized, now-empty copy.
        subprocess.run([args.ld, "-r", "--force-group-allocation", "-o", partials[name], *objs],
                       check=True)
    undef_of = {name: {s for s, t in nm(args.nm, [partials[name]], "-u") if t == "U"}
                for name, _ in mods}

    for name, _ in mods:
        partial, final = partials[name], os.path.join(args.outdir, f"{name}.o")
        eps = entry_points(args.nm, [partial])
        redefine = []
        if "prolog" in eps:
            redefine += ["--redefine-sym", f"{eps['prolog']}=mp_rel_{name}_prolog"]
        if "epilog" in eps:
            redefine += ["--redefine-sym", f"{eps['epilog']}=mp_rel_{name}_epilog"]

        # Another module's references count too: a symbol this module defines and a sibling needs,
        # with no definition outside any module, stays global.
        needed = set(undef_outside)
        for other, syms in undef_of.items():
            if other != name:
                needed |= syms
        entry_names = set(eps.values())
        local = sorted(s for s, t in nm(args.nm, [partial], "--defined-only", "-g")
                       if t not in "Uu" and s not in entry_names
                       and not (s in needed and s not in defined_outside))
        symfile = os.path.join(args.outdir, f"{name}.localize")
        open(symfile, "w").write("".join(f"{s}\n" for s in local))

        stage = os.path.join(args.outdir, f"{name}.renamed.o")
        subprocess.run([args.objcopy, *redefine, partial, stage], check=True)
        if local:
            subprocess.run([args.objcopy, f"--localize-symbols={symfile}", stage, final], check=True)
        else:
            # A module whose only globals are its own entry points (the shared entry-point stub
            # in tools/modules_port.txt, for instance) has nothing to localize, and objcopy
            # rejects an empty symbol list.
            subprocess.run([args.objcopy, stage, final], check=True)
        os.remove(stage)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("mode", choices=["registry", "scope"])
    ap.add_argument("--modules", required=True)
    ap.add_argument("--out")
    ap.add_argument("--others")
    ap.add_argument("--outdir")
    ap.add_argument("--ld", default="ld.bfd")
    ap.add_argument("--objcopy", default="objcopy")
    ap.add_argument("--nm", default="nm")
    args = ap.parse_args()
    (registry if args.mode == "registry" else scope)(args)


if __name__ == "__main__":
    sys.exit(main())
